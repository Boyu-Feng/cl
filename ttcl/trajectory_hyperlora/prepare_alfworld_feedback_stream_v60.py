"""Freeze a causal shared-experience stream and fixed accumulation probes.

Teacher trajectories were generated by v52b itself. Candidate arms replay that
common history; they do not independently collect the training prefix. The
probe tasks are exposed TRAIN development tasks, never a blind test.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from types import SimpleNamespace

from ttcl.trajectory_hyperlora.alfworld_bootstrap_own_success_v43 import ordered, action_rows
from ttcl.trajectory_hyperlora.alfworld_online_from_empty import digest, file_hash, records_from_episode
from ttcl.trajectory_hyperlora.audit_my_online_update_v28_reward import replay
from ttcl.trajectory_hyperlora.prepare_alfworld_off_goal_feedback_v57 import off_goal


def parser():
    p=argparse.ArgumentParser()
    p.add_argument('--teacher',type=Path,default=Path('results/trajectory_hyperlora/alfworld_online_own_trajectory_v52b_stream240_20261010.json'))
    p.add_argument('--source-report',type=Path,default=Path('results/trajectory_hyperlora/alf_sibling_train240_taskpair_current1000_20261006.json'))
    p.add_argument('--negative-review',type=Path,default=Path('data/annotations/alfworld_off_goal_feedback_v57_prefix120_20261010.json'))
    p.add_argument('--data-root',type=Path,default=Path('ttcl/data/alfworld_delta'))
    p.add_argument('--output',type=Path,default=Path('data/annotations/alfworld_feedback_stream_v60_20261010.json'))
    return p


def main():
    args=parser().parse_args()
    if args.output.exists():
        raise FileExistsError(args.output)
    teacher=json.loads(args.teacher.read_text())
    rows=teacher['rows'][:120]
    assert len(rows)==120 and [r['index'] for r in rows]==list(range(120))
    assert not teacher['failures']
    negative=json.loads(args.negative_review.read_text())
    assert negative['prefix_tasks']==120 and negative['prefix_rows_sha256']==digest(rows)
    assert negative['targets_sha256']==digest(negative['targets'])
    assert negative['runner_sha256']==file_hash(Path(__file__).with_name('prepare_alfworld_off_goal_feedback_v57.py'))
    negatives={i:[] for i in range(120)}
    for item in negative['targets']:
        content={k:v for k,v in item.items() if k not in ('input_content_sha256','reviewed_target','review_note')}
        assert item['reviewed_target'] and item['input_content_sha256']==digest(content)
        index=item['stream_index']; ep=rows[index]['online']
        assert item['episode_sha256']==digest(ep) and item['game']==rows[index]['game']
        step=ep['trajectory'][item['turn']]
        assert item['observed_action']==step['command'] and item['feedback']==step['observation']
        assert item['supervision']==off_goal(ep['initial_observation'],step['command'],step['observation'])
        negatives[index].append(item)
    ordered_rows=ordered(SimpleNamespace(source_report=args.source_report))
    stream=[]
    latest={}
    for i,row in enumerate(rows):
        old=ordered_rows[i]
        assert row['game']==old['game']
        ep=row['online']; game=args.data_root/row['game']
        assert ep['status']=='complete' and ep['reward'] in (0,1)
        replay(game,ep)
        actions=action_rows(game,ep) if ep['reward']==1 else []
        records=records_from_episode(ep)
        source=latest.get(old['family'])
        content={'index':i,'game':row['game'],'game_sha256':file_hash(game),
            'family':old['family'],'episode_sha256':digest(ep),'reward':ep['reward'],
            'source_index':source,'source_records':records,'positive_actions':actions,
            'negative_targets':negatives[i]}
        stream.append({**content,'input_content_sha256':digest(content),'reviewed_target':True})
        latest[old['family']]=i
        if (i+1)%20==0:
            print(json.dumps({'reviewed_prefix_tasks':i+1}),flush=True)
    probes=[]
    for i in range(120,144):
        row=ordered_rows[i]
        content={'index':i,'game':row['game'],'family':row['family'],
            'game_sha256':file_hash(args.data_root/row['game']),
            'initial_observation_sha256':digest(row['arms']['base']['initial_observation'])}
        probes.append({**content,'input_content_sha256':digest(content),'reviewed_target':True})
    config={'seed':42,'bootstrap_own_wins':8,'bootstrap_steps':300,'online_steps_per_event':20,
        'checkpoint_prefix_lengths':[40,80,120],'probe_tasks':24,'max_steps':30,
        'max_new_tokens':64,'actor_history_turns':2,'loop_guard_max':2,
        'negative_weight':.1,'bootstrap_lr':1e-4,'online_lr':1e-5,
        'rank':4,'layers':2,'hyper_shared_A_frozen_after_bootstrap':True,
        'source_selection':'Latest earlier teacher trajectory of the same family, regardless of outcome',
        'event':'After bootstrap, update on a new own success with an earlier same-family source or an episode with reviewed off-goal labels and an earlier same-family source',
        'positive_replay':'Current eligible success, otherwise latest eligible past success; source fixed to the trajectory preceding that positive target',
        'negative_replay':'Current eligible negative labels, otherwise latest eligible past negative episode; source fixed to its preceding same-family trajectory',
        'sampling':'Uniform with replacement within chosen positive/negative episodes using one seeded schedule shared by both arms',
        'no_negative_yet':'Positive CE only, identical target schedule in both arms',
        'arms':['hyper_online','hyper_frozen_bootstrap','online_static_lora','hyper_shifted_source_actions'],
        'primary_endpoint':'Prefix120 probe scores; prefix40/80 are descriptive accumulation checkpoints, not independent tests',
        'interpretation':'Same self-generated teacher stream replayed chronologically; exposed train development probes; no independent self-sampling or blind-generalization claim'}
    result={'protocol':'v60 chronological success plus public-goal-bound negative feedback; models train only on prefix120; fixed probes never enter memory or updates',
        'runner_sha256':file_hash(Path(__file__)),'teacher_prefix_sha256':digest(rows),
        'teacher_review_sha256':teacher['review_sha256'],'negative_review_sha256':file_hash(args.negative_review),
        'config':config,'config_sha256':digest(config),'stream':stream,'stream_sha256':digest(stream),
        'probes':probes,'probes_sha256':digest(probes)}
    with args.output.open('x') as f:
        json.dump(result,f,ensure_ascii=False,indent=2); f.write('\n')
    print(json.dumps({'reviewed_tasks':120,'own_successes':sum(x['reward'] for x in stream),
        'negative_targets':sum(len(x['negative_targets']) for x in stream),'fixed_probes':24}),flush=True)


if __name__=='__main__':
    main()
